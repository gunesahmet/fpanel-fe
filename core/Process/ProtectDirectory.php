class ProtectDirectory extends Process
{
    public function createDirectory($params = array())
    {
        try {
            return $this->socket->process('protectmng')
                ->job(array('create-dir'))
                ->params($params)
                ->create()
                ->send(300, $this->server_id)
                ->response();
        }
        catch (\Exception $e) {
            throw new \Exception($e->getMessage());
}
